// Fix F5: the signed-out Home without the row, and the new section in Filters.
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import puppeteer from "puppeteer-core";
const OUT = new URL("./outF5/", import.meta.url);
fs.mkdirSync(OUT, { recursive: true });
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH ?? "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true, args: ["--no-sandbox"], userDataDir: fileURLToPath(new URL("./profile", import.meta.url)) });
const page = await browser.newPage();
const shot = async n => { await new Promise(r => setTimeout(r, 1000)); await page.screenshot({ path: fileURLToPath(new URL(`${n}.png`, OUT)) }); console.log("shot", n); };
await page.goto("http://localhost:3100/login", { waitUntil: "networkidle2" }); await page.evaluate(() => localStorage.clear());
await page.setViewport({ width: 1536, height: 1000 });
await page.goto("http://localhost:3100/", { waitUntil: "networkidle2" }); await shot("home-d");
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2 });
await page.goto("http://localhost:3100/", { waitUntil: "networkidle2" });
await page.evaluate(() => window.scrollTo(0, 420)); await shot("home-m");
await page.goto("http://localhost:3100/listings?panel=1", { waitUntil: "networkidle2" });
await page.waitForSelector("[role=dialog]");
await page.evaluate(() => [...document.querySelectorAll("[role=dialog] button")].find(b => b.textContent.trim() === "Quiet home")?.click());
await page.evaluate(() => [...document.querySelectorAll("[role=dialog] h3")].find(h => h.textContent === "What matters to you?")?.scrollIntoView({ block: "center" }));
await shot("filters-m");
await page.evaluate(() => [...document.querySelectorAll("[role=dialog] button")].find(b => b.textContent.trim().startsWith("Show"))?.click());
await new Promise(r => setTimeout(r, 1500)); await shot("results-quiet-m");
await browser.close();
